def add_numbers(x,y):
    return x + y

def subtract_numbers(x,y):
    return x - y

def multiply(a,b):
    return a * b

def divide(a,b):
    return a / b

print("The addition of %d and %d is: %f " % (5, 2 , add_numbers(5,2)))

print("The subtraction of %d and %d is: %f " % (24, 7 , subtract_numbers(24,7)))

print("The multiplication of %d and %d is: %f " % (7, 2 , multiply(7,2)))

print("The division of %d and %d is: %.2f " % (25, 6 , divide(25,6)))

